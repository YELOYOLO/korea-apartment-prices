#!/usr/bin/env node
// Generates supabase/functions/_shared/kr/regions.ts from the official 법정동코드 전체자료
// (행정표준코드관리시스템, www.code.go.kr: 법정동코드목록조회 -> 법정동코드 전체자료).
//
//   node scripts/gen-regions.mjs "/path/to/법정동코드 전체자료.txt"
//
// Keeps existing (존재) 시군구 rows (code ddddd00000, not a 시도 row). A 시 that has
// 일반구 is dropped in favour of its 구: 실거래가 is reported per 구 (e.g. 수원시 41110
// is replaced by 장안구 41111, 권선구 41113, ...). The file is CP949 text.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const src = process.argv[2];
if (!src) {
  console.error("usage: node scripts/gen-regions.mjs <법정동코드 전체자료.txt>");
  process.exit(1);
}
const text = new TextDecoder("euc-kr").decode(readFileSync(src));
const rows = text
  .split(/\r?\n/)
  .slice(1)
  .map((l) => l.split("\t"))
  .filter((c) => c.length >= 3 && c[2].trim() === "존재")
  .map(([code, name]) => ({ code: code.trim(), name: name.trim() }));

const sido = new Map(rows.filter((r) => r.code.endsWith("00000000")).map((r) => [r.code.slice(0, 2), r.name]));
const sgg = rows.filter((r) => r.code.endsWith("00000") && r.code.slice(2, 5) !== "000");
// 세종특별자치시 (36110) has no separate 시도 row: it is its own 시도.
for (const r of sgg) if (!sido.has(r.code.slice(0, 2)) && !r.name.includes(" ")) sido.set(r.code.slice(0, 2), r.name);
const names = sgg.map((r) => r.name);
const regions = sgg
  .filter((r) => !names.some((n) => n !== r.name && n.startsWith(`${r.name} `)))
  .map((r) => {
    const sidoName = sido.get(r.code.slice(0, 2));
    if (!sidoName) throw new Error(`no 시도 for ${r.code}`);
    // "세종특별자치시" has no 시군구 level below the 시도: use the 시도 name.
    const local = r.name === sidoName ? sidoName : r.name.slice(sidoName.length + 1);
    return { code: r.code.slice(0, 5), sido: sidoName, name: local };
  });

const out = `// GENERATED by scripts/gen-regions.mjs from the official 법정동코드 전체자료
// (www.code.go.kr). Do not edit by hand; regenerate when 시군구 change.
// ${regions.length} 시군구 (LAWD_CD, 5 digits) in ${sido.size} 시도. Cities with 일반구 are listed by 구.

export interface KrRegion {
  /** LAWD_CD: first 5 digits of the 법정동코드. */
  code: string;
  /** 시도 as written in official records ("서울특별시", "강원특별자치도"). */
  sido: string;
  /** 시군구 ("종로구", "수원시 장안구"). */
  name: string;
}

export const KR_SIDO: readonly string[] = ${JSON.stringify([...sido.values()], null, 2)};

export const KR_REGIONS: readonly KrRegion[] = [
${regions.map((r) => `  { code: "${r.code}", sido: "${r.sido}", name: "${r.name}" },`).join("\n")}
];

const BY_CODE = new Map(KR_REGIONS.map((r) => [r.code, r]));

export function krRegion(code: string | null | undefined): KrRegion | undefined {
  return code ? BY_CODE.get(code) : undefined;
}

export function krRegionLabel(code: string | null | undefined): string {
  const r = krRegion(code);
  return r ? (r.name === r.sido ? r.sido : \`\${r.sido} \${r.name}\`) : (code ?? "");
}
`;
const dest = fileURLToPath(new URL("../supabase/functions/_shared/kr/regions.ts", import.meta.url));
writeFileSync(dest, out);
console.log(`wrote ${regions.length} 시군구 / ${sido.size} 시도 -> ${dest}`);
